import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';

const password = 'My new account password 2026';
test('register, verify inside Android, sign in, sign out and reset via email link', async ({ page }) => {
  const email = randomUUID() + '@example.com';
  await page.setViewportSize({ width: 360, height: 800 });
  await page.goto('/');
  await page.getByRole('button', { name: '注册账号', exact: true }).click();
  await page.getByLabel('邮箱', { exact: true }).fill(email);
  await page.getByLabel('密码', { exact: true }).fill(password);
  await page.getByLabel('确认密码').fill(password);
  await page.getByRole('button', { name: '注册并发送验证邮件' }).click();
  await expect(page.getByRole('heading', { name: '验证你的邮箱' })).toBeVisible();
  expect((await page.request.get('/api/state')).status()).toBe(401);
  const message = await (await page.request.get('/__test__/mail?email=' + encodeURIComponent(email))).json();
  const token = message.text.match(/token=([A-Za-z0-9_-]+)/)[1];
  await page.getByLabel('邮件中的验证凭证').fill(token);
  await page.getByRole('button', { name: '验证邮箱', exact: true }).click();
  await expect(page.getByRole('heading', { name: '欢迎回到ShutterCat' })).toBeVisible();
  await page.getByLabel('密码', { exact: true }).fill(password);
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page.locator('.coin-pill strong')).toHaveText('200');
  await page.getByRole('button', { name: '设置', exact: true }).click();
  await expect(page.getByText(email, { exact: false })).toBeVisible();
  await page.getByRole('button', { name: '退出登录', exact: true }).click();
  await expect(page.getByRole('heading', { name: '欢迎回到ShutterCat' })).toBeVisible();
  expect((await page.request.get('/api/state')).status()).toBe(401);
  await page.getByRole('button', { name: '忘记密码' }).click();
  await page.getByLabel('邮箱', { exact: true }).fill(email);
  await page.getByRole('button', { name: '发送重置邮件' }).click();
  await expect(page.getByRole('heading', { name: '设置新密码' })).toBeVisible();
  const reset = await (await page.request.get('/__test__/mail?email=' + encodeURIComponent(email))).json();
  const resetToken = reset.text.match(/token=([A-Za-z0-9_-]+)/)[1];
  await page.goto('/#auth=reset&token=' + resetToken);
  await expect(page.getByRole('heading', { name: '设置新密码' })).toBeVisible();
  await expect(page.getByLabel('邮件中的验证凭证')).toHaveValue(resetToken);
  expect(page.url()).not.toContain('token=');
  await page.getByLabel('邮箱', { exact: true }).fill(email);
  await page.getByLabel('新密码', { exact: true }).fill(password + ' changed');
  await page.getByLabel('确认密码').fill(password + ' changed');
  await page.getByRole('button', { name: '重置密码', exact: true }).click();
  await expect(page.getByRole('heading', { name: '欢迎回到ShutterCat' })).toBeVisible();
  await page.getByLabel('密码', { exact: true }).fill(password + ' changed');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page.locator('.coin-pill strong')).toHaveText('200');
});

test('verification links survive StrictMode and remain usable on a narrow screen', async ({ page }) => {
  const email = randomUUID() + '@example.com';
  expect((await page.request.post('/api/auth/register', { data: { email, password } })).status()).toBe(202);
  const message = await (await page.request.get('/__test__/mail?email=' + encodeURIComponent(email))).json();
  const token = message.text.match(/token=([A-Za-z0-9_-]+)/)[1];
  await page.setViewportSize({ width: 320, height: 720 });
  await page.goto('/#auth=verify&token=' + token);
  await expect(page.getByRole('heading', { name: '验证你的邮箱' })).toBeVisible();
  await expect(page.getByLabel('邮件中的验证凭证')).toHaveValue(token);
  expect(page.url()).not.toContain('token=');
  await page.getByLabel('邮箱', { exact: true }).fill(email);
  await page.getByLabel('密码', { exact: true }).fill(password);
  await page.getByRole('button', { name: '验证邮箱', exact: true }).click();
  await expect(page.getByRole('heading', { name: '欢迎回到ShutterCat' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.getByRole('button', { name: '注册账号', exact: true }).click();
  await page.getByText('已有旧版匿名账号？', { exact: true }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
});

test('verified users can permanently delete their account and public deletion instructions are available', async ({ page }) => {
  const email = randomUUID() + '@example.com';
  expect((await page.request.post('/__test__/seed', { data: { email, password } })).status()).toBe(200);
  await page.goto('/');
  await page.getByLabel('邮箱', { exact: true }).fill(email);
  await page.getByLabel('密码', { exact: true }).fill(password);
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await page.getByRole('button', { name: '设置', exact: true }).click();
  await page.getByRole('button', { name: '删除账号和全部数据', exact: true }).click();
  await page.getByLabel('当前密码', { exact: true }).fill(password);
  await page.getByRole('checkbox', { name: /不可撤销/ }).check();
  await page.getByRole('button', { name: '永久删除账号', exact: true }).click();
  await expect(page.getByRole('heading', { name: '欢迎回到ShutterCat' })).toBeVisible();
  expect((await page.request.get('/api/state')).status()).toBe(401);
  expect((await page.request.get('/delete-account.html')).status()).toBe(200);
});
